// Returns true if the service should be code-generated with schema-based serde.
// Services may also be opted in with the `forceSchemaBasedServices` property, a comma-separated
// list of service shape ID prefixes, i.e. `-PforceSchemaBasedServices=com.amazonaws.lambda#`
fun useForceSchemaBased(service: ServiceShape): Boolean {
    val overrides = getProperty("forceSchemaBasedServices")
        ?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() }
        .orEmpty()
    val serviceId = service.id.toString()
    return (schemaBasedRestJson1Services + overrides).any { serviceId.startsWith(it) }
}

// Returns an AwsService model for every JSON file found in in directory defined by property `modelsDirProp`
fun discoverServices(): List<AwsService> {
    val modelsDirProp: String by project
    val modelsDir = project.file(modelsDirProp)
    val models = fileTree(modelsDir).filter { it.isFile }.files.toMutableSet()
    val onlyIncludeModels = getProperty("onlyIncludeModels")
    val excludeModels = getProperty("excludeModels")
    var filteredModels = models

    onlyIncludeModels?.let {
        val modelsToInclude = it.split(",").map { "$it.json" }.map { it.trim() }
        filteredModels = models.filter { modelsToInclude.contains(it.name) }.toMutableSet()
    }
    // If a model is specified in both onlyIncludeModels and excludeModels, it is excluded.
    excludeModels?.let {
        val modelsToExclude = it.split(",").map { "$it.json" }.map { it.trim() }
        filteredModels = filteredModels.filterNot { modelsToExclude.contains(it.name) }.toMutableSet()
    }

    return filteredModels
        .map { file ->
            val model = Model.assembler().addImport(file.absolutePath).assemble().result.get()
            val services: List<ServiceShape> = model.shapes(ServiceShape::class.java).sorted().toList()
            require(services.size == 1) { "Expected one service per aws model, but found ${services.size} in ${file.absolutePath}: ${services.map { it.id }}" }
            val service = services.first()
            file to service
        }.flatMap { (file, service) ->
            val serviceApi = service.getTrait(software.amazon.smithy.aws.traits.ServiceTrait::class.java).orNull()
                ?: error { "Expected aws.api#service trait attached to model ${file.absolutePath}" }
            val (name, version, _) = file.name.split(".")
            val packageName = "AWS${serviceApi.sdkId.filterNot { it.isWhitespace() }.replaceFirstChar { it.titlecase() }}"

            logger.info("discovered service: ${serviceApi.sdkId}")
            val forceSchemaBased = useForceSchemaBased(service)

            val publicService = AwsService(
                name = service.id.toString(),
                packageName = packageName,
                packageVersion = packageVersion,
                modelFile = file,
                projectionName = name + "." + version.lowercase(),
                sdkId = serviceApi.sdkId,
                gitRepo = "https://github.com/awslabs/aws-sdk-swift",
                visibility = "public",
                internalClient = false,
                operations = listOf(),
                forceSchemaBased = forceSchemaBased,
            )

            // Codegen internal clients used by credential resolvers.
            if (serviceApi.sdkId in setOf("STS", "SSO", "SSO OIDC", "Cognito Identity", "Signin")) {
                val internalProjection = AwsService(
                    name = service.id.toString(),
                    packageName = "Internal$packageName",
                    packageVersion = packageVersion,
                    modelFile = file,
                    projectionName = "${name}.${version.lowercase()}_internal",
                    sdkId = serviceApi.sdkId,
                    gitRepo = "https://github.com/awslabs/aws-sdk-swift",
                    visibility = "package",
                    internalClient = true,
                    operations = internalOperations(serviceApi.sdkId),
                    forceSchemaBased = forceSchemaBased,
                )
                listOf(publicService, internalProjection)
            } else {
                listOf(publicService)
            }
        }
}

// This function returns operations to be included when an internal service is built.
fun internalOperations(sdkId: String): List<String> {
    return when (sdkId) {
        "STS" -> listOf(
            "com.amazonaws.sts#AssumeRole",
            "com.amazonaws.sts#AssumeRoleWithWebIdentity",
        )
        "SSO" -> listOf(
            "com.amazonaws.sso#GetRoleCredentials",
        )
        "SSO OIDC" -> listOf(
            "com.amazonaws.ssooidc#CreateToken",
        )
        "Cognito Identity" -> listOf(
            "com.amazonaws.cognitoidentity#GetId",
            "com.amazonaws.cognitoidentity#GetCredentialsForIdentity",
        )
        "Signin" -> listOf(
            "com.amazonaws.signin#CreateOAuth2Token",
        )
        else -> emptyList()
    }
}

