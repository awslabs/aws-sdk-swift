/**
 * Service specific model extras
 */
val AwsService.modelExtrasDir: String
    get() = rootProject.file("$packageName/Tests/AdditionalServiceTests/$packageName/models").absolutePath

tasks.register("stageSdks") {
    group = "codegen"
    description = "relocate generated SDK artifacts from build directory to correct locations"
    doLast {
        discoveredServices.forEach {
            logger.info("copying ${it.outputDir} source to ${it.sourcesDir}")
            copy {
                from(it.outputDir)
                into(it.sourcesDir)
                exclude { details ->
                    // Exclude Package.swift
                    val fileIsPackageManifest = details.file.name.endsWith("Package.swift")

                    // Exclude `SmokeTests` directory
                    val fileIsSmokeTests = details.file.name.endsWith("SmokeTests")

                    // Exclude service client test files
                    val fileIsServiceClientTests = details.relativePath.startsWith("Tests")

                    fileIsPackageManifest || fileIsSmokeTests || fileIsServiceClientTests
                }
            }

            logger.info("copying ${it.outputDir}/SmokeTests to SmokeTests")
            copy {
                from("${it.outputDir}/SmokeTests")
                into(rootProject.file("SmokeTests").absolutePath)
            }
        }
    }
}

// Generates a smithy-build.json file by creating a new projection for every
// JSON model file found in aws-models/. The generated smithy-build.json file is
// not committed to git since it's rebuilt each time codegen is performed.
tasks.register("generate-smithy-build") {
    group = "codegen"
    description = "generate smithy-build.json"
    doFirst {
        projectDir.resolve("smithy-build.json").writeText(generateSmithyBuild(discoveredServices))
    }
}

tasks.named("smithyBuild") {
    dependsOn("generate-smithy-build")
}

